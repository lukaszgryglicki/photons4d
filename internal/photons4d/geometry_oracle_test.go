// Every primitive is checked here against a description of its solid that
// shares no code with its intersection routine: an implicit function in world
// space (negative inside), built from the definition of the shape and its own
// world->local transform. A ray result is compared with the first change of
// side found by marching along the ray, and the normal with the numeric
// gradient of that function.
type solidUT struct {
	name     string
	min, max Point4
	hit      func(Point4, Vector4) (objectHit, bool)
	f        func(Point4) Real
	steps    int // marching steps of the reference
	size     Real
}

func oracleLocal(R Mat4, C Point4, x Point4) Vector4 {
	d := [4]Real{x.X - C.X, x.Y - C.Y, x.Z - C.Z, x.W - C.W}
	var l [4]Real
	for k := 0; k < 4; k++ {
		for r := 0; r < 4; r++ {
			l[k] += R.M[r][k] * d[r]
		}
	}
	return Vector4{l[0], l[1], l[2], l[3]}
}

func oraclePerms(a [4]Real, parity int) [][4]Real {
	var out [][4]Real
	idx := []int{0, 1, 2, 3}
	var rec func(k int)
	rec = func(k int) {
		if k == 4 {
			inv := 0
			for i := 0; i < 4; i++ {
				for j := i + 1; j < 4; j++ {
					if idx[i] > idx[j] {
						inv++
					}
				}
			}
			if parity < 0 || inv&1 == parity {
				out = append(out, [4]Real{a[idx[0]], a[idx[1]], a[idx[2]], a[idx[3]]})
			}
			return
		}
		for i := k; i < 4; i++ {
			idx[k], idx[i] = idx[i], idx[k]
			rec(k + 1)
			idx[k], idx[i] = idx[i], idx[k]
		}
	}
	rec(0)
	return out
}

func oracleSigns(in [][4]Real) []Vector4 {
	seen := map[[4]int64]bool{}
	var out []Vector4
	for _, v := range in {
		for s := 0; s < 16; s++ {
			w := v
			skip := false
			for i := 0; i < 4; i++ {
				if (s>>i)&1 == 1 {
					if w[i] == 0 {
						skip = true
						break
					}
					w[i] = -w[i]
				}
			}
			if skip {
				continue
			}
			k := [4]int64{int64(math.Round(w[0] * 1e9)), int64(math.Round(w[1] * 1e9)), int64(math.Round(w[2] * 1e9)), int64(math.Round(w[3] * 1e9))}
			if !seen[k] {
				seen[k] = true
				out = append(out, Vector4{w[0], w[1], w[2], w[3]})
			}
		}
	}
	return out
}

// oracleIcosians returns the 120 unit quaternions of the binary icosahedral
// group, generated by closing two of them under multiplication: the vertices
// of a 600-cell.
func oracleIcosians() []Vector4 {
	phi := (1 + math.Sqrt(5)) / 2
	mul := func(a, b [4]Real) [4]Real {
		return [4]Real{
			a[0]*b[0] - a[1]*b[1] - a[2]*b[2] - a[3]*b[3],
			a[0]*b[1] + a[1]*b[0] + a[2]*b[3] - a[3]*b[2],
			a[0]*b[2] - a[1]*b[3] + a[2]*b[0] + a[3]*b[1],
			a[0]*b[3] + a[1]*b[2] - a[2]*b[1] + a[3]*b[0],
		}
	}
	key := func(q [4]Real) [4]int64 {
		return [4]int64{int64(math.Round(q[0] * 1e9)), int64(math.Round(q[1] * 1e9)), int64(math.Round(q[2] * 1e9)), int64(math.Round(q[3] * 1e9))}
	}
	gens := [][4]Real{{0.5, 0.5, 0.5, 0.5}, {phi / 2, 0.5, 1 / (2 * phi), 0}}
	set := map[[4]int64]bool{key([4]Real{1, 0, 0, 0}): true}
	queue := [][4]Real{{1, 0, 0, 0}}
	out := []Vector4{{1, 0, 0, 0}}
	for len(queue) > 0 && len(out) <= 120 {
		q := queue[0]
		queue = queue[1:]
		for _, g := range gens {
			r := mul(q, g)
			if k := key(r); !set[k] {
				set[k] = true
				queue = append(queue, r)
				out = append(out, Vector4{r[0], r[1], r[2], r[3]})
			}
		}
	}
	return out
}

// oracleClassic120 returns the 600 vertices of the 120-cell from its textbook
// coordinates (circumradius sqrt(8)). The table is usually printed with even
// permutations; the 120-cell that is dual to the 600-cell of even
// permutations of (phi, 1, 1/phi, 0)/2 takes the odd ones.
func oracleClassic120() []Vector4 {
	phi := (1 + math.Sqrt(5)) / 2
	s5 := math.Sqrt(5)
	var raw [][4]Real
	for _, b := range [][4]Real{{0, 0, 2, 2}, {1, 1, 1, s5}, {1 / (phi * phi), phi, phi, phi}, {1 / phi, 1 / phi, 1 / phi, phi * phi}} {
		raw = append(raw, oraclePerms(b, -1)...)
	}
	for _, b := range [][4]Real{{0, 1 / (phi * phi), 1, phi * phi}, {0, 1 / phi, phi, s5}, {1 / phi, 1, phi, 2}} {
		raw = append(raw, oraclePerms(b, 1)...)
	}
	return oracleSigns(raw)
}

func oracleSameSet(a, b []Vector4) bool {
	if len(a) != len(b) {
		return false
	}
	for _, x := range a {
		found := false
		for _, y := range b {
			if x.Sub(y).Len() < 1e-9 {
				found = true
				break
			}
		}
		if !found {
			return false
		}
	}
	return true
}

func TestCell600And120VertexSetsAgainstIndependentConstructions(t *testing.T) {
	if !oracleSameSet(verts600Unit(), oracleIcosians()) {
		t.Fatalf("verts600Unit is not the binary icosahedral group")
	}
	classic := oracleClassic120()
	if len(classic) != 600 {
		t.Fatalf("classical 120-cell table gave %d vertices", len(classic))
	}
	for i := range classic {
		classic[i] = classic[i].Norm()
	}
	if !oracleSameSet(verts120Unit(), classic) {
		t.Fatalf("verts120Unit differs from the classical coordinates of the 120-cell")
	}

	phi := (1 + math.Sqrt(5)) / 2
	for _, c := range []struct {
		name    string
		vs      []Vector4
		edge    Real
		valence int
	}{
		{"600-cell", verts600Unit(), 1 / phi, 12},
		{"120-cell", verts120Unit(), (3 - math.Sqrt(5)) / math.Sqrt(8), 4},
	} {
		for i, v := range c.vs {
			n := 0
			for j, w := range c.vs {
				if i == j {
					continue
				}
				d := v.Sub(w).Len()
				if d < c.edge-1e-9 {
					t.Fatalf("%s: vertices %d and %d are closer (%.12g) than the edge %.12g", c.name, i, j, d, c.edge)
				}
				if d < c.edge+1e-9 {
					n++
				}
			}
			if n != c.valence {
				t.Fatalf("%s: vertex %d has %d edges, want %d", c.name, i, n, c.valence)
			}
		}
	}
}

func oracleSolids(t *testing.T, rng *rand.Rand, size Real) []solidUT {
	t.Helper()
	rnd := func() Real { return (rng.Float64() - 0.5) * 2 * math.Pi }
	rot := Rot4{XY: rnd(), XZ: rnd(), XW: rnd(), YZ: rnd(), YW: rnd(), ZW: rnd()}
	ctr := Point4{rng.Float64() - 0.5, rng.Float64() - 0.5, rng.Float64() - 0.5, rng.Float64() - 0.5}
	rs := func() Real { return (0.5 + rng.Float64()) * size }
	sc := Vector4{rs(), rs(), rs(), rs()}
	white, none, half, ior := RGB{1, 1, 1}, RGB{}, RGB{0.5, 0.5, 0.5}, RGB{1.5, 1.5, 1.5}
	sq := func(x Real) Real { return x * x }

	var out []solidUT
	add := func(name string, err error, min, max Point4, steps int, f func(Point4) Real, hit func(Point4, Vector4) (objectHit, bool)) {
		t.Helper()
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		d := Vector4{max.X - min.X, max.Y - min.Y, max.Z - min.Z, max.W - min.W}.Len()
		out = append(out, solidUT{name: name, min: min, max: max, hit: hit, f: f, steps: steps, size: d})
	}
	// local coordinates divided by the scale
	scaled := func(R Mat4, x Point4) Vector4 {
		l := oracleLocal(R, ctr, x)
		return Vector4{l.X / sc.X, l.Y / sc.Y, l.Z / sc.Z, l.W / sc.W}
	}
	support := func(ns []Vector4, q Vector4) Real {
		m := math.Inf(-1)
		for _, n := range ns {
			if d := n.Dot(q); d > m {
				m = d
			}
		}
		return m
	}
	const cheap, costly = 1000, 200

	{
		o, err := NewHyperSphere(ctr, sc, rot, white, none, half, half, ior)
		add("hypersphere", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return q.Dot(q) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayHyperSphere(O, D, o) })
	}
	{
		// membership by barycentric coordinates of the five vertices
		o, err := NewCell5(ctr, sc, rot, white, none, half, half, ior)
		V := o.Verts
		var m [4][8]Real
		for r := 0; r < 4; r++ {
			for c := 0; c < 4; c++ {
				m[r][c] = [4]Real{V[c+1].X - V[0].X, V[c+1].Y - V[0].Y, V[c+1].Z - V[0].Z, V[c+1].W - V[0].W}[r]
			}
			m[r][4+r] = 1
		}
		for c := 0; c < 4; c++ {
			p := c
			for r := c + 1; r < 4; r++ {
				if math.Abs(m[r][c]) > math.Abs(m[p][c]) {
					p = r
				}
			}
			m[c], m[p] = m[p], m[c]
			d := m[c][c]
			for j := 0; j < 8; j++ {
				m[c][j] /= d
			}
			for r := 0; r < 4; r++ {
				if r != c {
					f := m[r][c]
					for j := 0; j < 8; j++ {
						m[r][j] -= f * m[c][j]
					}
				}
			}
		}
		add("cell5", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			d := [4]Real{x.X - V[0].X, x.Y - V[0].Y, x.Z - V[0].Z, x.W - V[0].W}
			least, sum := math.Inf(1), Real(0)
			for i := 0; i < 4; i++ {
				b := Real(0)
				for j := 0; j < 4; j++ {
					b += m[i][4+j] * d[j]
				}
				sum += b
				least = math.Min(least, b)
			}
			return -math.Min(least, 1-sum)
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCell5(O, D, o) })
	}
	{
		o, err := NewCell8(ctr, sc, rot, white, none, half, half, ior)
		add("cell8", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Max(math.Max(math.Abs(q.X), math.Abs(q.Y)), math.Max(math.Abs(q.Z), math.Abs(q.W))) - 0.5
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCell8(O, D, o) })
	}
	{
		o, err := NewCell16(ctr, sc, rot, white, none, half, half, ior)
		add("cell16", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Abs(q.X) + math.Abs(q.Y) + math.Abs(q.Z) + math.Abs(q.W) - 1/math.Sqrt2
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCell16(O, D, o) })
	}
	{
		// hull of the permutations of (±1,±1,0,0)/sqrt(2): |q_i| <= 1 and sum |q_i| <= 2 before the division
		o, err := NewCell24(ctr, sc, rot, white, none, half, half, ior)
		add("cell24", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x).Mul(math.Sqrt2)
			a := [4]Real{math.Abs(q.X), math.Abs(q.Y), math.Abs(q.Z), math.Abs(q.W)}
			return math.Max(math.Max(math.Max(a[0], a[1]), math.Max(a[2], a[3]))-1, (a[0]+a[1]+a[2]+a[3])/2-1)
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCell24(O, D, o) })
	}
	icosians := oracleIcosians()
	classic := oracleClassic120()
	for i := range classic {
		classic[i] = classic[i].Norm()
	}
	{
		o, err := NewCell120(ctr, sc, rot, white, none, half, half, ior)
		add("cell120", err, o.AABBMin, o.AABBMax, costly, func(x Point4) Real {
			return support(icosians, scaled(o.R, x)) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCellPoly(O, D, &o.cellPoly) })
	}
	{
		o, err := NewCell600(ctr, sc, rot, white, none, half, half, ior)
		add("cell600", err, o.AABBMin, o.AABBMax, costly, func(x Point4) Real {
			return support(classic, scaled(o.R, x)) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCellPoly(O, D, &o.cellPoly) })
	}
	for _, kind := range []string{"5", "8", "16", "24", "120", "600"} {
		core, spike, sharp := 0.3+0.3*rng.Float64(), 0.3+0.5*rng.Float64(), 3+6*rng.Float64()
		o, err := NewStarCell(kind, ctr, sc, core, spike, sharp, rot, white, none, half, half, ior)
		steps := cheap
		if err == nil && len(o.Dirs) > 24 {
			steps = costly
		}
		add("star"+kind, err, o.AABBMin, o.AABBMax, steps, func(x Point4) Real {
			q := scaled(o.R, x)
			r := q.Len()
			if r == 0 {
				return -core
			}
			return r - (core + spike*math.Pow(math.Max(0, support(o.Dirs, q)/r), sharp))
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayStarCell(O, D, o) })
	}
	{
		o, err := NewSpherinder(ctr, sc, rot, white, none, half, half, ior)
		add("spherinder", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Max(sq(q.X)+sq(q.Y)+sq(q.Z)-1, math.Abs(q.W)-1)
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRaySpherinder(O, D, o) })
	}
	{
		o, err := NewHyperCone(ctr, sc, rot, white, none, half, half, ior)
		add("hypercone", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			u := (q.W + 1) / 2
			if u < 0 {
				return 1 - u
			}
			return math.Max(math.Sqrt(sq(q.X)+sq(q.Y)+sq(q.Z))-u, q.W-1)
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayHyperCone(O, D, o) })
	}
	{
		hl := (0.3 + rng.Float64()) * size
		o, err := NewHyperCapsule(ctr, sc, hl, rot, white, none, half, half, ior)
		add("hypercapsule", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			l := oracleLocal(o.R, ctr, x)
			return sq(l.X/sc.X) + sq(l.Y/sc.Y) + sq(l.Z/sc.Z) + sq(math.Max(0, math.Abs(l.W)-hl)/sc.W) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayHyperCapsule(O, D, o) })
	}
	{
		R, r := 0.6+0.6*rng.Float64(), 0.1+0.4*rng.Float64()
		o, err := NewSpheritorus(ctr, sc, R, r, rot, white, none, half, half, ior)
		add("spheritorus", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return sq(math.Hypot(q.X, q.W)-R) + sq(q.Y) + sq(q.Z) - r*r
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRaySpheritorus(O, D, o) })
	}
	{
		R1, R2, r := 0.6+0.6*rng.Float64(), 0.6+0.6*rng.Float64(), 0.1+0.4*rng.Float64()
		o, err := NewDuotorus(ctr, sc, R1, R2, r, rot, white, none, half, half, ior)
		add("duotorus", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return sq(math.Hypot(q.X, q.Y)-R1) + sq(math.Hypot(q.Z, q.W)-R2) - r*r
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayDuotorus(O, D, o) })
	}
	{
		R, r := 0.6+0.6*rng.Float64(), 0.1+0.4*rng.Float64()
		o, err := NewTorisphere(ctr, sc, R, r, rot, white, none, half, half, ior)
		add("torisphere", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return sq(math.Sqrt(sq(q.X)+sq(q.Y)+sq(q.Z))-R) + sq(q.W) - r*r
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayTorisphere(O, D, o) })
	}
	{
		R := 0.9 + 0.6*rng.Float64()
		M := R * (0.3 + 0.2*rng.Float64())
		r := M * (0.2 + 0.5*rng.Float64())
		o, err := NewDitorus(ctr, sc, R, M, r, rot, white, none, half, half, ior)
		add("ditorus", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return sq(math.Hypot(math.Hypot(q.X, q.Y)-R, q.Z)-M) + sq(q.W) - r*r
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayDitorus(O, D, o) })
	}
	{
		o, err := NewDuocylinder(ctr, sc, rot, white, none, half, half, ior)
		add("duocylinder", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Max(sq(q.X)+sq(q.Y), sq(q.Z)+sq(q.W)) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayDuocylinder(O, D, o) })
	}
	{
		o, err := NewCubinder(ctr, sc, rot, white, none, half, half, ior)
		add("cubinder", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Max(sq(q.X)+sq(q.Y), math.Max(math.Abs(q.Z), math.Abs(q.W))) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCubinder(O, D, o) })
	}
	{
		p := 1.2 + 6*rng.Float64()
		o, err := NewSuperquadric(ctr, sc, p, rot, white, none, half, half, ior)
		add("superquadric", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Pow(math.Abs(q.X), p) + math.Pow(math.Abs(q.Y), p) + math.Pow(math.Abs(q.Z), p) + math.Pow(math.Abs(q.W), p) - 1
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRaySuperquadric(O, D, o) })
	}
	{
		lo, up := 0.2+rng.Float64(), 0.2+rng.Float64()
		o, err := NewHyperFrustum(ctr, sc, lo, up, rot, white, none, half, half, ior)
		add("hyperfrustum", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Max(math.Sqrt(sq(q.X)+sq(q.Y)+sq(q.Z))-((lo+up)/2+(up-lo)/2*q.W), math.Abs(q.W)-1)
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayHyperFrustum(O, D, o) })
	}
	for _, pq := range [][2]int{{3, 3}, {5, 3}, {4, 6}, {7, 12}} {
		// polygon in polar form: rho*cos(angle from the middle of its sector) <= cos(pi/n)
		poly := func(x, y Real, n int) Real {
			th := math.Atan2(y, x)
			if th < 0 {
				th += 2 * math.Pi
			}
			w := 2 * math.Pi / Real(n)
			return math.Hypot(x, y)*math.Cos(math.Mod(th, w)-w/2) - math.Cos(w/2)
		}
		p, q := pq[0], pq[1]
		o, err := NewDuoprism(ctr, sc, p, q, rot, white, none, half, half, ior)
		add(fmt.Sprintf("duoprism%d-%d", p, q), err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			l := scaled(o.R, x)
			return math.Max(poly(l.X, l.Y, p), poly(l.Z, l.W, q))
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCellPoly(O, D, &o.cellPoly) })
	}

	// gauge of a regular polygon with the circumradius 1 and a corner on the first axis
	polygon := func(x, y Real, n int) Real {
		th := math.Atan2(y, x)
		if th < 0 {
			th += 2 * math.Pi
		}
		w := 2 * math.Pi / Real(n)
		return math.Hypot(x, y) * math.Cos(math.Mod(th, w)-w/2) / math.Cos(w/2)
	}
	polytope := func(name string, o *Polytope, err error, steps int, g func(Vector4) Real) {
		t.Helper()
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		add(name, nil, o.AABBMin, o.AABBMax, steps, func(x Point4) Real { return g(scaled(o.R, x)) },
			func(O Point4, D Vector4) (objectHit, bool) { return intersectRayCellPoly(O, D, &o.cellPoly) })
	}
	for _, d := range []string{"o3x3o3o", "x3x3o3x", "x4o3x3o", "o4x3x3x", "x3o4o3x", "x3x4x3x", "o5o3x3o", "x5o3o3x", "x5x3x3x"} {
		for _, dual := range []bool{false, true} {
			if dual && d != "o3x3o3o" && d != "x4o3x3o" && d != "o5o3x3o" {
				continue
			}
			o, err := NewPolychoron(d, dual, ctr, sc, rot, white, none, half, half, ior)
			k := newKaleidoscope(t, d)
			name, g := "polychoron "+d, k.gauge
			if dual {
				name, g = "dual "+name, k.dualGauge
			}
			polytope(name, o, err, cheap, func(q Vector4) Real { return g(q) - 1 })
		}
	}
	{
		// the 600-cell cut by the planes of the neighbours of the vertices that are left out
		phi := (1 + math.Sqrt(5)) / 2
		inradius := phi * phi / math.Sqrt(8)
		cut := func(gone []Vector4) func(Vector4) Real {
			return func(q Vector4) Real {
				return math.Max(support(classic, q)/inradius, support(gone, q)/(phi/2)) - 1
			}
		}
		o, err := NewPolychoron("snub 24-cell", false, ctr, sc, rot, white, none, half, half, ior)
		polytope("snub 24-cell", o, err, costly, cut(oracleHurwitzUnits()))
		o, err = NewPolychoron("grand antiprism", false, ctr, sc, rot, white, none, half, half, ior)
		polytope("grand antiprism", o, err, costly, cut(oracleDecagonRings()))
	}
	for _, c := range []struct{ shape, base string }{
		{"prism", "truncated icosahedron"}, {"prism", "snub cube"}, {"prism", "5-gonal antiprism"},
		{"pyramid", "dodecahedron"}, {"pyramid", "7-gonal prism"}, {"bipyramid", "rhombicuboctahedron"}, {"bipyramid", "snub dodecahedron"},
	} {
		verts, _, err := uniformPolyhedron(c.base)
		if err != nil {
			t.Fatalf("%s: %v", c.base, err)
		}
		faces := oracleHull3(verts)
		h := math.Inf(1)
		for i := range verts {
			for j := i + 1; j < len(verts); j++ {
				h = math.Min(h, verts[i].Sub(verts[j]).Len()/2)
			}
		}
		shape := c.shape
		o, err := NewPolyhedralSolid(shape, c.base, ctr, sc, rot, white, none, half, half, ior)
		polytope(c.base+" "+shape, o, err, cheap, func(q Vector4) Real {
			g := support(faces, Vector4{q.X, q.Y, q.Z, 0})
			switch shape {
			case "prism":
				return math.Max(g-1, math.Abs(q.W)-h)
			case "pyramid":
				return math.Max(g-(q.W+1)/2, q.W-1)
			}
			return g + math.Abs(q.W) - 1
		})
	}
	for _, pq := range [][2]int{{3, 3}, {4, 4}, {5, 8}} {
		p, q := pq[0], pq[1]
		o, err := NewDuopyramid(ctr, sc, p, q, rot, white, none, half, half, ior)
		polytope(fmt.Sprintf("duopyramid%d-%d", p, q), o, err, cheap, func(l Vector4) Real {
			return polygon(l.X, l.Y, p) + polygon(l.Z, l.W, q) - 1
		})
	}
	// The reference of the star polychora is slow; TestStarPolychoraAgainstFlagSimplices
	// checks all of them at other sizes with exact intervals.
	for _, kind := range []string{"{5/2,5,3}", "{5/2,3,3}"} {
		if size != 1 {
			break
		}
		o, err := NewStarPolychoron(kind, ctr, sc, rot, white, none, half, half, ior)
		flags := newOracleFlags(t, kind)
		add("star polychoron "+kind, err, o.AABBMin, o.AABBMax, 60, func(x Point4) Real {
			return flags.distance(scaled(o.R, x))
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayStarPolychoron(O, D, o) })
	}
	for _, c := range []struct {
		shape string
		g     func(q Vector4) Real
	}{
		{"<(II)(II)>", func(q Vector4) Real { return math.Hypot(q.X, q.Y) + math.Hypot(q.Z, q.W) }},
		{"<(III)I>", func(q Vector4) Real { return math.Sqrt(sq(q.X)+sq(q.Y)+sq(q.Z)) + math.Abs(q.W) }},
		{"([II]II)", func(q Vector4) Real { return math.Sqrt(sq(math.Max(math.Abs(q.X), math.Abs(q.Y))) + sq(q.Z) + sq(q.W)) }},
		{"(<II>(II))", func(q Vector4) Real { return math.Sqrt(sq(math.Abs(q.X)+math.Abs(q.Y)) + sq(q.Z) + sq(q.W)) }},
		{"<[(II)I]I>", func(q Vector4) Real { return math.Max(math.Hypot(q.X, q.Y), math.Abs(q.Z)) + math.Abs(q.W) }},
		{"[<II>(II)]", func(q Vector4) Real { return math.Max(math.Abs(q.X)+math.Abs(q.Y), math.Hypot(q.Z, q.W)) }},
		{"<I[I(II)]>", func(q Vector4) Real { return math.Abs(q.X) + math.Max(math.Abs(q.Y), math.Hypot(q.Z, q.W)) }},
	} {
		g := c.g
		o, err := NewBracketope(c.shape, ctr, sc, rot, white, none, half, half, ior)
		add("bracketope "+c.shape, err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real { return g(scaled(o.R, x)) - 1 },
			func(O Point4, D Vector4) (objectHit, bool) { return intersectRayConvexSolid(O, D, o) })
	}
	convex := func(name string, o *ConvexSolid, err error, g func(Vector4) Real) {
		t.Helper()
		add(name, err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real { return g(scaled(o.R, x)) },
			func(O Point4, D Vector4) (objectHit, bool) { return intersectRayConvexSolid(O, D, o) })
	}
	{
		o, err := NewConinder(ctr, sc, rot, white, none, half, half, ior)
		convex("coninder", o, err, func(q Vector4) Real {
			return math.Max(math.Max(math.Hypot(q.X, q.Y)-(q.Z+1)/2, q.Z-1), math.Abs(q.W)-1)
		})
		o, err = NewCylindrone(ctr, sc, rot, white, none, half, half, ior)
		convex("cylindrone", o, err, func(q Vector4) Real {
			u := (q.W + 1) / 2
			return math.Max(math.Max(math.Hypot(q.X, q.Y)-u, math.Abs(q.Z)-u), q.W-1)
		})
		o, err = NewDicone(ctr, sc, rot, white, none, half, half, ior)
		convex("dicone", o, err, func(q Vector4) Real {
			u := (q.W + 1) / 2
			return math.Max(math.Hypot(q.X, q.Y)-u, math.Abs(q.Z)-(1-u))
		})
		for _, n := range []int{3, 4, 7} {
			n := n
			o, err = NewPrismicCylinder(n, ctr, sc, rot, white, none, half, half, ior)
			convex(fmt.Sprintf("prismic cylinder %d", n), o, err, func(q Vector4) Real {
				return math.Max(math.Hypot(q.X, q.Y), polygon(q.Z, q.W, n)) - 1
			})
		}
	}
	{
		R, r := 0.6+0.6*rng.Float64(), 0.1+0.4*rng.Float64()
		o, err := NewTorinder(ctr, sc, R, r, rot, white, none, half, half, ior)
		add("torinder", err, o.AABBMin, o.AABBMax, cheap, func(x Point4) Real {
			q := scaled(o.R, x)
			return math.Max(sq(math.Hypot(q.X, q.Y)-R)+sq(q.Z)-r*r, math.Abs(q.W)-1)
		}, func(O Point4, D Vector4) (objectHit, bool) { return intersectRayTorinder(O, D, o) })
	}
	return out
}

// oracleFirstCrossing marches over (0, tFar] and returns the first change of
// side, refined by bisection.
func oracleFirstCrossing(f func(Point4) Real, O Point4, D Vector4, tFar Real, n int) (Real, bool) {
	in := f(O) <= 0
	prev := Real(0)
	for i := 1; i <= n; i++ {
		t := tFar * Real(i) / Real(n)
		if (f(O.Add(D.Mul(t))) <= 0) != in {
			lo, hi := prev, t
			for k := 0; k < 60; k++ {
				m := 0.5 * (lo + hi)
				if (f(O.Add(D.Mul(m))) <= 0) != in {
					hi = m
				} else {
					lo = m
				}
			}
			return 0.5 * (lo + hi), true
		}
		prev = t
	}
	return 0, false
}

type oracleTally struct {
	rays, hits                                       int
	missed, late, phantom, side, normal, away, boxed int
	notes                                            []string
}

func (c *oracleTally) note(format string, a ...any) {
	if len(c.notes) < 4 {
		c.notes = append(c.notes, fmt.Sprintf(format, a...))
	}
}

func (c *oracleTally) bad() int {
	return c.missed + c.late + c.phantom + c.side + c.normal + c.away + c.boxed
}

// oracleCheck compares one ray with the reference and returns the hit.
func oracleCheck(s *solidUT, O Point4, D Vector4, c *oracleTally, kind string) (objectHit, bool) {
	c.rays++
	unit := 1 + s.size
	mid := Point4{(s.min.X + s.max.X) / 2, (s.min.Y + s.max.Y) / 2, (s.min.Z + s.max.Z) / 2, (s.min.W + s.max.W) / 2}
	tFar := Vector4{O.X - mid.X, O.Y - mid.Y, O.Z - mid.Z, O.W - mid.W}.Len() + s.size + 0.5
	inside := func(x Point4) bool { return s.f(x) <= 0 }

	h, ok := s.hit(O, D)
	tRef, okRef := oracleFirstCrossing(s.f, O, D, tFar, s.steps)
	if !ok {
		if okRef {
			c.missed++
			c.note("%s missed: O=%v D=%v first crossing at t=%.12g", kind, O, D, tRef)
		}
		return h, false
	}
	c.hits++

	// The reported point must separate the two sides (a thin part may need a narrow window).
	var before, after bool
	crossing := false
	for w := 2e-6 * unit; w > 1e-12*unit && !crossing; w /= 10 {
		before = inside(O.Add(D.Mul(h.t - w)))
		after = inside(O.Add(D.Mul(h.t + w)))
		crossing = before != after
	}
	if !crossing {
		c.phantom++
		c.note("%s phantom hit: O=%v D=%v t=%.12g (reference %.12g %v)", kind, O, D, h.t, tRef, okRef)
		return h, true
	}
	if okRef && h.t > tRef+1e-6*unit {
		c.late++
		c.note("%s late hit: O=%v D=%v t=%.12g, first crossing at %.12g", kind, O, D, h.t, tRef)
	}
	if h.inv != before {
		c.side++
		c.note("%s wrong side flag: O=%v D=%v t=%.12g inv=%v", kind, O, D, h.t, h.inv)
	}

	P := O.Add(D.Mul(h.t))
	grad := func(e Real) Vector4 {
		return Vector4{
			s.f(Point4{P.X + e, P.Y, P.Z, P.W}) - s.f(Point4{P.X - e, P.Y, P.Z, P.W}),
			s.f(Point4{P.X, P.Y + e, P.Z, P.W}) - s.f(Point4{P.X, P.Y - e, P.Z, P.W}),
			s.f(Point4{P.X, P.Y, P.Z + e, P.W}) - s.f(Point4{P.X, P.Y, P.Z - e, P.W}),
			s.f(Point4{P.X, P.Y, P.Z, P.W + e}) - s.f(Point4{P.X, P.Y, P.Z, P.W - e}),
		}.Mul(1 / (2 * e))
	}
	g, fine := grad(1e-5*s.size), grad(1e-7*s.size)
	if gl := fine.Len(); gl > 0 && math.Abs(s.f(P))/gl > 1e-9*unit {
		c.away++
		c.note("%s hit point off the surface by %.3g: O=%v D=%v t=%.12g", kind, math.Abs(s.f(P))/gl, O, D, h.t)
	}
	angle := func(a, b Vector4) Real { return math.Acos(math.Max(-1, math.Min(1, a.Norm().Dot(b.Norm())))) }
	// Away from edges and seams (where the two gradients differ) the normal is the unit gradient.
	if angle(g, fine) < 1e-4 {
		if math.Abs(h.Nw.Len()-1) > 1e-9 || angle(g, h.Nw) > 1e-4 {
			c.normal++
			c.note("%s wrong normal: P=%v N=%v gradient=%v", kind, P, h.Nw, g.Norm())
		}
	}
	slack := 1e-7 * unit
	if P.X < s.min.X-slack || P.X > s.max.X+slack || P.Y < s.min.Y-slack || P.Y > s.max.Y+slack ||
		P.Z < s.min.Z-slack || P.Z > s.max.Z+slack || P.W < s.min.W-slack || P.W > s.max.W+slack {
		c.boxed++
		c.note("%s hit point outside the AABB: P=%v", kind, P)
	}
	return h, true
}

func TestPrimitivesAgainstIndependentSolids(t *testing.T) {
	sizes := []Real{1, 0.05, 20}
	raysOut := 160
	if testing.Short() {
		sizes = sizes[:1]
		raysOut = 60
	}
	rng := rand.New(rand.NewSource(20261118))
	tally := map[string]*oracleTally{}
	var names []string
	for _, size := range sizes {
		solids := oracleSolids(t, rng, size)
		for i := range solids {
			s := &solids[i]
			c := tally[s.name]
			if c == nil {
				c = &oracleTally{}
				tally[s.name] = c
				names = append(names, s.name)
			}
			mid := Point4{(s.min.X + s.max.X) / 2, (s.min.Y + s.max.Y) / 2, (s.min.Z + s.max.Z) / 2, (s.min.W + s.max.W) / 2}
			within := func(k Real) Point4 {
				return Point4{
					mid.X + (rng.Float64()-0.5)*(s.max.X-s.min.X)*k, mid.Y + (rng.Float64()-0.5)*(s.max.Y-s.min.Y)*k,
					mid.Z + (rng.Float64()-0.5)*(s.max.Z-s.min.Z)*k, mid.W + (rng.Float64()-0.5)*(s.max.W-s.min.W)*k,
				}
			}

			// the AABB holds the whole solid
			for n := 0; n < 4000; n++ {
				x := within(1.6)
				if s.f(x) <= 0 && (x.X < s.min.X || x.X > s.max.X || x.Y < s.min.Y || x.Y > s.max.Y ||
					x.Z < s.min.Z || x.Z > s.max.Z || x.W < s.min.W || x.W > s.max.W) {
					c.boxed++
					c.note("point of the solid outside the AABB: %v", x)
				}
			}

			type surf struct {
				P Point4
				N Vector4
				D Vector4
			}
			var surfs []surf
			// from outside towards the solid
			for n := 0; n < raysOut; n++ {
				O := mid.Add(unitS3(rng).Mul(-(s.size + 1)))
				T := within(1)
				D := Vector4{T.X - O.X, T.Y - O.Y, T.Z - O.Z, T.W - O.W}.Norm()
				if h, ok := oracleCheck(s, O, D, c, "outside"); ok {
					surfs = append(surfs, surf{O.Add(D.Mul(h.t)), h.Nw, D})
				}
			}
			// from inside the solid
			for n, tries := 0, 0; n < raysOut/2 && tries < raysOut*200; tries++ {
				if O := within(1); s.f(O) < 0 {
					n++
					oracleCheck(s, O, unitS3(rng), c, "inside")
				}
			}
			// the way the tracer continues from a hit: reflected, refracted and scattered rays
			for _, sf := range surfs {
				dirs := []Vector4{reflect4(sf.D, sf.N).Norm(), sampleDiffuseDir(sf.N, rng)}
				if T, ok := refract4(sf.D, sf.N, 1/1.5); ok {
					dirs = append(dirs, T.Norm())
				}
				for _, d := range dirs {
					oracleCheck(s, sf.P.Add(d.Mul(bumpShift)), d, c, "continued")
				}
			}
			// along the surface, a little above or below it
			for n, sf := range surfs {
				if n >= raysOut/2 {
					break
				}
				U, V, W := orthonormal3Fast(sf.N)
				a, b, w := sampleS2(rng)
				T := U.Mul(a).Add(V.Mul(b)).Add(W.Mul(w)).Norm()
				off := (rng.Float64()*2 - 1) * math.Pow(10, -1-5*rng.Float64()) * (1 + s.size)
				oracleCheck(s, sf.P.Add(sf.N.Mul(off)).Add(T.Mul(-(s.size + 1))), T, c, "grazing")
			}
		}
	}
	for _, name := range names {
		c := tally[name]
		if c.hits == 0 {
			t.Errorf("%s: no hit in %d rays", name, c.rays)
		}
		if c.bad() > 0 {
			t.Errorf("%s: %d rays, %d hits: missed=%d late=%d phantom=%d side=%d normal=%d off-surface=%d aabb=%d\n  %s",
				name, c.rays, c.hits, c.missed, c.late, c.phantom, c.side, c.normal, c.away, c.boxed, fmt.Sprint(c.notes))
		}
	}
}
