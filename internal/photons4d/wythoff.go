package photons4d

import (
	"fmt"
	"math"
)

// pointSet stores distinct points and finds a stored point within a small
// distance of a given one.
type pointSet struct {
	cells map[[4]int64][]int
	pts   []Vector4
}

const (
	pointSetGrid = 1e-5
	pointSetTol  = 1e-8
)

func newPointSet() *pointSet {
	return &pointSet{cells: make(map[[4]int64][]int)}
}

func (s *pointSet) find(v Vector4) int {
	c := [4]Real{v.X, v.Y, v.Z, v.W}
	var lo, hi [4]int64
	for i := 0; i < 4; i++ {
		lo[i] = int64(math.Floor((c[i]-pointSetTol)/pointSetGrid + 0.5))
		hi[i] = int64(math.Floor((c[i]+pointSetTol)/pointSetGrid + 0.5))
	}
	for a := lo[0]; a <= hi[0]; a++ {
		for b := lo[1]; b <= hi[1]; b++ {
			for d := lo[2]; d <= hi[2]; d++ {
				for e := lo[3]; e <= hi[3]; e++ {
					for _, i := range s.cells[[4]int64{a, b, d, e}] {
						if s.pts[i].Sub(v).Len() <= pointSetTol {
							return i
						}
					}
				}
			}
		}
	}
	return -1
}

// add stores v unless it is there already and tells whether it was new.
func (s *pointSet) add(v Vector4) (int, bool) {
	if i := s.find(v); i >= 0 {
		return i, false
	}
	k := [4]int64{
		int64(math.Floor(v.X/pointSetGrid + 0.5)), int64(math.Floor(v.Y/pointSetGrid + 0.5)),
		int64(math.Floor(v.Z/pointSetGrid + 0.5)), int64(math.Floor(v.W/pointSetGrid + 0.5)),
	}
	s.pts = append(s.pts, v)
	s.cells[k] = append(s.cells[k], len(s.pts)-1)
	return len(s.pts) - 1, true
}

func vecAt(v Vector4, i int) Real {
	switch i {
	case 0:
		return v.X
	case 1:
		return v.Y
	case 2:
		return v.Z
	default:
		return v.W
	}
}

func vecWith(v Vector4, i int, x Real) Vector4 {
	switch i {
	case 0:
		v.X = x
	case 1:
		v.Y = x
	case 2:
		v.Z = x
	default:
		v.W = x
	}
	return v
}

// coxeterMirrors returns the unit normals of the mirrors of a linear Coxeter
// diagram: mirror k and mirror k+1 meet at the angle pi/marks[k] (a mark may
// be a fraction such as 5/2), all other pairs are perpendicular. Mirror k
// uses the first k+1 coordinates only. It also returns the dual vectors:
// dual[i] lies on every mirror but the mirror i, with dual[i]·normal[i] = 1.
func coxeterMirrors(marks []Real) (normals, dual []Vector4, err error) {
	m := len(marks) + 1
	if m < 2 || m > 4 {
		return nil, nil, fmt.Errorf("a Coxeter diagram of %d mirrors is not supported", m)
	}
	normals = make([]Vector4, m)
	normals[0] = Vector4{1, 0, 0, 0}
	for k := 1; k < m; k++ {
		if !(marks[k-1] > 1) {
			return nil, nil, fmt.Errorf("branch mark %g of a Coxeter diagram must be above 1", marks[k-1])
		}
		a := -math.Cos(math.Pi/marks[k-1]) / vecAt(normals[k-1], k-1)
		if !(a*a < 1-1e-12) {
			return nil, nil, fmt.Errorf("the Coxeter diagram with the marks %v has no finite group", marks)
		}
		normals[k] = vecWith(vecWith(Vector4{}, k-1, a), k, math.Sqrt(1-a*a))
	}
	dual = make([]Vector4, m)
	for i := 0; i < m; i++ {
		prev := Real(0)
		for j := 0; j < m; j++ {
			rhs := Real(0)
			if i == j {
				rhs = 1
			}
			if j > 0 {
				rhs -= vecAt(normals[j], j-1) * prev
			}
			prev = rhs / vecAt(normals[j], j)
			dual[i] = vecWith(dual[i], j, prev)
		}
	}
	return normals, dual, nil
}

func mirrorImage(v, normal Vector4) Vector4 {
	return v.Sub(normal.Mul(2 * v.Dot(normal)))
}

// Largest orbit of a point under a finite reflection group in 4D (the group
// of the 120-cell has 14400 elements).
const maxOrbit = 14400

// reflectionOrbit returns all images of seed under the group generated by
// the mirrors.
func reflectionOrbit(mirrors []Vector4, seed Vector4) ([]Vector4, error) {
	set := newPointSet()
	set.add(seed)
	for i := 0; i < len(set.pts); i++ {
		for _, n := range mirrors {
			set.add(mirrorImage(set.pts[i], n))
		}
		if len(set.pts) > maxOrbit {
			return nil, fmt.Errorf("the reflection group is not finite")
		}
	}
	return set.pts, nil
}

// affineRank returns the dimension of the flat spanned by the points (at most 4).
func affineRank(pts []Vector4) int {
	var basis []Vector4
	for _, p := range pts[1:] {
		d := p.Sub(pts[0])
		scale := d.Len()
		for _, b := range basis {
			d = d.Sub(b.Mul(d.Dot(b)))
		}
		if l := d.Len(); l > 1e-6*math.Max(1, scale) {
			basis = append(basis, d.Mul(1/l))
			if len(basis) == 4 {
				break
			}
		}
	}
	return len(basis)
}

// supportPlanes turns directions into facet planes n·x <= 1 of the convex
// hull of verts: a direction is kept if the vertices farthest along it span a
// flat of the dimension dim (3 for the cells of a polychoron).
func supportPlanes(verts, dirs []Vector4, dim int) []Vector4 {
	set := newPointSet()
	var on []Vector4
	for _, u := range dirs {
		h := math.Inf(-1)
		for _, v := range verts {
			if d := u.Dot(v); d > h {
				h = d
			}
		}
		if !(h > 1e-9) {
			continue
		}
		on = on[:0]
		for _, v := range verts {
			if u.Dot(v) > h-1e-9 {
				on = append(on, v)
			}
		}
		if affineRank(on) == dim {
			set.add(u.Mul(1 / h))
		}
	}
	return set.pts
}

// wythoffPolytope returns the vertices (on the unit sphere) and the facet
// planes n·x <= 1 of the uniform polytope of a linear Coxeter diagram with
// the given branch marks and ringed nodes: a polyhedron in XYZ for two marks,
// a polychoron for three. The facets lie square to the images of the dual
// vectors of the mirrors.
func wythoffPolytope(marks []Real, rings []bool) (verts, planes []Vector4, err error) {
	if len(rings) != len(marks)+1 {
		return nil, nil, fmt.Errorf("a diagram with %d branches has %d nodes, not %d", len(marks), len(marks)+1, len(rings))
	}
	mirrors, dual, err := coxeterMirrors(marks)
	if err != nil {
		return nil, nil, err
	}
	var seed Vector4
	for i, on := range rings {
		if on {
			seed = seed.Add(dual[i])
		}
	}
	if seed.Len() == 0 {
		return nil, nil, fmt.Errorf("a uniform polytope needs at least one ringed node")
	}
	if verts, err = reflectionOrbit(mirrors, seed.Norm()); err != nil {
		return nil, nil, err
	}
	var dirs []Vector4
	for _, d := range dual {
		o, err := reflectionOrbit(mirrors, d.Norm())
		if err != nil {
			return nil, nil, err
		}
		dirs = append(dirs, o...)
	}
	planes = supportPlanes(verts, dirs, len(marks))
	if len(planes) < len(marks)+2 {
		return nil, nil, fmt.Errorf("the diagram gives a flat figure")
	}
	return verts, planes, nil
}

// hullPlanes returns the facet planes n·x <= 1 of the convex hull of the
// vertices of a polytope around the origin whose edges all have the least
// distance between two vertices: every facet lies in the flat through a
// vertex and dim-1 of its neighbours. dim is 4 for a polychoron and 3 for a
// polyhedron in XYZ.
func hullPlanes(verts []Vector4, dim int) []Vector4 {
	edge := math.Inf(1)
	for i := range verts {
		for j := i + 1; j < len(verts); j++ {
			if d := verts[i].Sub(verts[j]).Len(); d < edge {
				edge = d
			}
		}
	}
	set := newPointSet()
	var near []Vector4
	for i, v := range verts {
		near = near[:0]
		for j, w := range verts {
			if i != j && v.Sub(w).Len() <= edge*(1+1e-6) {
				near = append(near, w.Sub(v))
			}
		}
		try := func(n Vector4) {
			if n.Len() < 1e-9*edge*edge*edge {
				return
			}
			h := n.Dot(v)
			if math.Abs(h) < 1e-12 {
				return
			}
			n = n.Mul(1 / h)
			for _, w := range verts {
				if n.Dot(w) > 1+1e-9 {
					return
				}
			}
			set.add(n)
		}
		for a := 0; a < len(near); a++ {
			for b := a + 1; b < len(near); b++ {
				if dim == 3 {
					try(cross3_4D(near[a], near[b], Vector4{0, 0, 0, edge}))
					continue
				}
				for c := b + 1; c < len(near); c++ {
					try(cross3_4D(near[a], near[b], near[c]))
				}
			}
		}
	}
	return set.pts
}
